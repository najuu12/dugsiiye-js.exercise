let x=15;
let y="15";

//equal to operator
console.log(x ==y);
//not equal to operator
console.log(x !=y);
//strict equal to operator
console.log(x ===y);
//strict not equal to operator
console.log(x !==y);    

//greater than operator
console.log(x>y);
//less than operator
console.log(x<y);
//greater than or equal to operator
console.log(x>=y);  

//less than or equal to operator
console.log(x<=y);